#!/usr/bin/env python3
"""Generate self-contained downloads from the shared core and OS adapters."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
APIS = ("uptime", "process_start", "desktop_backend", "is_wsl", "ssh_options",
        "chrome_base", "chrome_launch", "install_node", "install_hint")


def render(target):
    common = (ROOT / "lib/common.sh").read_text()
    header = "# Generated by scripts/build-profiles.py; edit scripts/lib/ instead.\n"
    if target == "auto":
        header += ('case "$(uname -s)" in\n'
                   '    Darwin) _CLAUDE_PROXY_PLATFORM=macos;;\n'
                   '    Linux) _CLAUDE_PROXY_PLATFORM=linux;;\n'
                   '    *) echo "[Err] Supported platforms: macOS, Linux and WSL." >&2; return 1 2>/dev/null || exit 1;;\n'
                   'esac\n')
        targets = ("macos", "linux")
    else:
        expected = "Darwin" if target == "macos" else "Linux"
        header += (f'if [ "$(uname -s)" != {expected} ]; then\n'
                   f'    echo "[Err] This profile is for {target}. Use claude-proxy.sh for automatic selection." >&2\n'
                   '    return 1 2>/dev/null || exit 1\nfi\n'
                   f'_CLAUDE_PROXY_PLATFORM={target}\n')
        targets = (target,)
    adapters = "# BEGIN PLATFORM ADAPTERS\n"
    for os_name in targets:
        adapters += (ROOT / f"lib/platform-{os_name}.sh").read_text() + "\n"
    for api in APIS:
        adapters += f"_platform_{api}() {{\n"
        if target == "auto":
            adapters += ('    case "$(uname -s)" in\n'
                         f'        Darwin) _macos_{api} "$@";;\n'
                         f'        Linux) _linux_{api} "$@";;\n'
                         '        *) return 1;;\n    esac\n')
        else:
            adapters += f'    _{target}_{api} "$@"\n'
        adapters += "}\n"
    # Explicit notification backend is also used by the isolated transport tests.
    adapters += '_platform_desktop_send() {\n    case "$1" in\n'
    for os_name in targets:
        backend = "macos" if os_name == "macos" else "linux"
        adapters += f'        {backend}) _{os_name}_desktop_send "$@";;\n'
    adapters += '        *) return 1;;\n    esac\n}\n# END PLATFORM ADAPTERS\n'
    assert common.count("# @PLATFORM_ADAPTERS@") == 1
    return header + common.replace("# @PLATFORM_ADAPTERS@", adapters.rstrip())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated profiles are stale")
    args = parser.parse_args()
    stale = []
    for target, filename in (("auto", "claude-proxy.sh"), ("macos", "claude-proxy-macos.sh"),
                             ("linux", "claude-proxy-linux.sh")):
        path = ROOT / filename
        content = render(target)
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(filename)
        else:
            path.write_text(content)
    if stale:
        print("Stale generated profiles: " + ", ".join(stale), file=sys.stderr)
        print("Run python3 scripts/build-profiles.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
